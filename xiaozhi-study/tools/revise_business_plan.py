def replace_body_paragraph(paragraph, lead, body):
    """Replace text while matching the template's body font and bold lead-in."""
    for run in list(paragraph.runs):
        paragraph._p.remove(run._r)

    pieces = []
    if lead:
        pieces.append((lead, True))
    if body:
        pieces.append((body, False))
    if not pieces:
        pieces.append(("", False))

    for text, bold in pieces:
        run = paragraph.add_run(text)
        run.font.name = LATIN_FONT
        run.font.size = BODY_SIZE
        run.font.bold = bold
        run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), BODY_FONT)


def validate_sections(document):
    counts = {}
    for title, (start, end, limit) in LIMITS.items():
        body = "".join(p.text for p in document.paragraphs[start + 1:end])
        compact = "".join(body.split())
        counts[title] = (len(compact), limit)
        if len(compact) > limit:
            raise ValueError(f"{title} exceeds {limit} characters: {len(compact)}")
    return counts


def main():
    document = Document(SOURCE)
    if len(document.paragraphs) <= max(REPLACEMENTS):
        raise ValueError("The source document structure does not match the expected template")

    for index, (lead, body) in REPLACEMENTS.items():
        replace_body_paragraph(document.paragraphs[index], lead, body)

    counts = validate_sections(document)
    document.core_properties.title = "第十二届中国研究生智慧城市技术与创意设计大赛商业计划书（修订版）"
    document.save(TARGET)

    print(f"created={TARGET}")
    print(f"size={TARGET.stat().st_size}")
    for title, (count, limit) in counts.items():
        print(f"{title}: {count}/{limit}")


if __name__ == "__main__":
    main()
